import { ref } from 'vue'

function storedLocale() {
    try { return localStorage.getItem('timetable-language') === 'en' ? 'en' : 'th' } catch { return 'th' }
}
export const locale = ref(storedLocale())
export function setLocale(value) {
    if (!['th', 'en'].includes(value)) return
    locale.value = value
    try { localStorage.setItem('timetable-language', value) } catch { /* Preference still works in this tab. */ }
    if (typeof document !== 'undefined') document.documentElement.lang = value
}
if (typeof document !== 'undefined') document.documentElement.lang = locale.value

